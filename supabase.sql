-- ============================================================
-- Historial de cambios. Lo llenan triggers de la base de datos,
-- así queda registrado todo cambio a miembros y equipos sin
-- importar desde dónde se haga (registro, lote, restauración,
-- edición, SQL). Nadie puede escribir ni borrar el historial desde
-- la app: solo leerlo con sesión iniciada.
--   cambios (editar) = { "campo": [antes, después], ... }
--   cambios (borrar un miembro) = copia de sus datos, para poder restaurarlo
-- ============================================================
create table if not exists public.historial (
  id bigint generated by default as identity primary key,
  fecha timestamptz not null default now(),
  usuario text,
  accion text not null check (accion in ('crear', 'editar', 'borrar')),
  tabla text not null,
  registro_id bigint,
  nombre text,
  cambios jsonb not null default '{}'::jsonb
);
create index if not exists historial_fecha on public.historial (fecha desc);
create index if not exists historial_registro on public.historial (tabla, registro_id, fecha desc);
alter table public.historial enable row level security;
drop policy if exists "historial_select" on public.historial;
create policy "historial_select" on public.historial for select to authenticated using (true);
revoke insert, update, delete on public.historial from anon, authenticated;

create or replace function public.registrar_historial()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  claims jsonb := nullif(current_setting('request.jwt.claims', true), '')::jsonb;
  quien text := coalesce(claims->>'email', case when claims is null then 'administrador (SQL)' end, 'desconocido');
  viejo jsonb;
  nuevo jsonb;
  cambios jsonb := '{}'::jsonb;
  k text;
  quien_nombre text;
begin
  if tg_op <> 'INSERT' then viejo := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then nuevo := to_jsonb(new); end if;

  if tg_table_name = 'miembros' then
    quien_nombre := coalesce(nuevo->>'nombres', viejo->>'nombres');
    if tg_op = 'UPDATE' then
      for k in select jsonb_object_keys(nuevo) loop
        continue when k in ('id', 'planillaHash', 'planillaPhash');
        if (viejo->k) is distinct from (nuevo->k) then
          if k = 'foto' then
            -- Solo se anota que cambió (las fotos pueden ser muy pesadas)
            cambios := cambios || jsonb_build_object('foto', jsonb_build_array(
              case when viejo->>'foto' is null then null else 'foto' end,
              case when nuevo->>'foto' is null then null else 'foto nueva' end));
          else
            cambios := cambios || jsonb_build_object(k, jsonb_build_array(viejo->k, nuevo->k));
          end if;
        end if;
      end loop;
      if cambios = '{}'::jsonb then return null; end if;
    elsif tg_op = 'DELETE' then
      -- Copia para poder restaurarlo (la foto solo si es un enlace, no base64)
      cambios := viejo - 'planillaPhash';
      if length(coalesce(viejo->>'foto', '')) > 2000 then cambios := cambios - 'foto'; end if;
    end if;
  else
    quien_nombre := (select p->>'nombre' from jsonb_array_elements(coalesce(nuevo, viejo)->'integrantes') p
                     where p->>'rol' = 'Líder' limit 1);
    if tg_op = 'UPDATE' and (viejo->'integrantes') is not distinct from (nuevo->'integrantes') then
      return null;
    end if;
    cambios := jsonb_build_object('integrantes', jsonb_build_array(viejo->'integrantes', nuevo->'integrantes'));
  end if;

  insert into public.historial (usuario, accion, tabla, registro_id, nombre, cambios)
  values (quien,
          case tg_op when 'INSERT' then 'crear' when 'UPDATE' then 'editar' else 'borrar' end,
          tg_table_name,
          coalesce((nuevo->>'id')::bigint, (viejo->>'id')::bigint),
          quien_nombre,
          cambios);
  return null;
end;
$$;
revoke execute on function public.registrar_historial() from public, anon, authenticated;

drop trigger if exists trg_historial_miembros on public.miembros;
create trigger trg_historial_miembros
  after insert or update or delete on public.miembros
  for each row execute function public.registrar_historial();

drop trigger if exists trg_historial_equipos on public.equipos;
create trigger trg_historial_equipos
  after insert or update or delete on public.equipos
  for each row execute function public.registrar_historial();

-- ============================================================
-- Keep-alive: evita que Supabase pause el proyecto gratuito por
-- inactividad (lo pausa tras 7 días sin uso). Un cron externo
-- (Vercel /api/keepalive y GitHub Actions) llama a keepalive()
-- cada día; la función escribe una fila, así cuenta como uso real
-- de la base de datos. No expone ningún dato de la membresía.
-- ============================================================
create table if not exists public.keepalive (
  id int primary key default 1 check (id = 1),
  ultimo timestamptz not null default now(),
  origen text,
  total bigint not null default 0
);
alter table public.keepalive enable row level security;
revoke all on public.keepalive from anon, authenticated;

create or replace function public.keepalive(origen text default 'desconocido')
returns timestamptz
language sql
security definer
set search_path = ''
as $$
  insert into public.keepalive (id, ultimo, origen, total)
    values (1, now(), left(origen, 40), 1)
    on conflict (id) do update
      set ultimo = now(), origen = left(excluded.origen, 40), total = public.keepalive.total + 1
  returning ultimo;
$$;
revoke execute on function public.keepalive(text) from public;
grant execute on function public.keepalive(text) to anon, authenticated;

